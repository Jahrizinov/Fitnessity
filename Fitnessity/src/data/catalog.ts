export const movementOf = (ex: Exercise) =>
  Object.entries(movements).find(([, movement]) =>
    movement.ids.includes(ex.id)
  )?.[0] ||
  ex.movement ||
  '';
export const exerciseTip = (ex: Exercise) =>
  movements[movementOf(ex)]?.tip ||
  'Voer de oefening rustig en gecontroleerd uit.';
export const repUnit = (ex: Exercise) =>
  ex.measurement === 'seconds' ? 'sec' : 'reps';

